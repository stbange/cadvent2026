lower = {}
for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
    rows = G[c]
    small = [rows[0], rows[2], rows[3], rows[4], rows[6]]
    lower[c.lower()] = [".....", "....."] + small
G.update(lower)
out = []
for code in range(32, 127):
    rows = G[chr(code)]
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), chr(code)
    vals = [sum((1 << (4 - i)) for i, ch in enumerate(r) if ch == '#') for r in rows]
    c = chr(code)
    label = {'\\': 'backslash', '*': 'star'}.get(c, c)
    out.append("    {" + ", ".join("0x%02x" % v for v in vals) + "}, /* " + label + " */")
print("\n".join(out))
