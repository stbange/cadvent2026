T = 0.5  # wall thickness


def emit(s):
    out.append(s)


def box(x0, y0, z0, x1, y1, z1, mat, kind="box"):
    emit(f"{kind} {x0:g} {y0:g} {z0:g} {x1:g} {y1:g} {z1:g} {mat}")


def wall_x(x, z0, z1, y0, y1, mat, openings=()):
    """Wall along Z at constant x (thickness centred on x) with door openings (z0, z1, top)."""
    segs = [(z0, z1)]
    for (oa, ob, top) in openings:
        new = []
        for (a, b) in segs:
            if ob <= a or oa >= b:
                new.append((a, b))
                continue
            if oa > a:
                new.append((a, oa))
            if ob < b:
                new.append((ob, b))
            if top < y1:
                box(x - T / 2, top, max(a, oa), x + T / 2, y1, min(b, ob), mat)
        segs = new
    for (a, b) in segs:
        if b - a > 0.01:
            box(x - T / 2, y0, a, x + T / 2, y1, b, mat)


def wall_z(z, x0, x1, y0, y1, mat, openings=()):
    segs = [(x0, x1)]
    for (oa, ob, top) in openings:
        new = []
        for (a, b) in segs:
            if ob <= a or oa >= b:
                new.append((a, b))
                continue
            if oa > a:
                new.append((a, oa))
            if ob < b:
                new.append((ob, b))
            if top < y1:
                box(max(a, oa), top, z - T / 2, min(b, ob), y1, z + T / 2, mat)
        segs = new
    for (a, b) in segs:
        if b - a > 0.01:
            box(a, y0, z - T / 2, b, y1, z + T / 2, mat)


def room(x0, x1, z0, z1, y0, h, wall, floor, ceil, n=(), s=(), w=(), e=(), skip=""):
    box(x0 - T, y0 - 0.5, z0 - T, x1 + T, y0, z1 + T, floor)
    if "c" not in skip:
        box(x0 - T, y0 + h, z0 - T, x1 + T, y0 + h + 0.5, z1 + T, ceil)
    if "n" not in skip:
        wall_z(z0 - T / 2, x0 - T, x1 + T, y0, y0 + h, wall, n)
    if "s" not in skip:
        wall_z(z1 + T / 2, x0 - T, x1 + T, y0, y0 + h, wall, s)
    if "w" not in skip:
        wall_x(x0 - T / 2, z0, z1, y0, y0 + h, wall, w)
    if "e" not in skip:
        wall_x(x1 + T / 2, z0, z1, y0, y0 + h, wall, e)


