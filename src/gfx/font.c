const uint8_t *cadv_font_glyph(int ch)
{
    if (ch < 32 || ch > 126) {
        ch = '?';
    }
    return k_glyphs[ch - 32];
}

bool cadv_font_pixel(int ch, int x, int y)
{
    if (x < 0 || y < 0 || x >= CADV_FONT_GLYPH_W || y >= CADV_FONT_GLYPH_H) {
        return false;
    }
    return (cadv_font_glyph(ch)[y] >> (4 - x)) & 1u;
}

void cadv_font_cell(int ch, int *x, int *y)
{
    int i;
    if (ch < 32 || ch > 127) {
        ch = '?';
    }
    i = ch - 32;
    *x = (i % 16) * 8;
    *y = (i / 16) * 8;
}

void cadv_font_build_atlas(uint8_t *rgba)
{
    int ch;
    memset(rgba, 0, (size_t)CADV_FONT_ATLAS_W * CADV_FONT_ATLAS_H * 4u);
    for (ch = 32; ch <= 127; ++ch) {
        int cx;
        int cy;
        int x;
        int y;
        cadv_font_cell(ch, &cx, &cy);
        for (y = 0; y < 8; ++y) {
            for (x = 0; x < 8; ++x) {
                bool on = ch == 127 ? true : cadv_font_pixel(ch, x, y);
                uint8_t *p = rgba + (((size_t)(cy + y) * CADV_FONT_ATLAS_W) + (size_t)(cx + x)) * 4u;
                if (on) {
                    p[0] = p[1] = p[2] = p[3] = 255;
                }
            }
        }
    }
}

void cadv_font_measure(const char *text, int *w, int *h)
{
    int line = 0;
    int maxw = 0;
    int lines = 1;
    for (; *text; ++text) {
        if (*text == '\n') {
            ++lines;
            line = 0;
            continue;
        }
        line += CADV_FONT_ADVANCE;
        if (line > maxw) {
            maxw = line;
        }
    }
    *w = maxw > 0 ? maxw - 1 : 0; /* no trailing spacing column */
    *h = lines * CADV_FONT_LINE - 2;
}
